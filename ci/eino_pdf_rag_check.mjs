import fs from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const read = (p) => fs.readFileSync(new URL(p, root), 'utf8');
const eino = read('services/api/src/eino.js');
const index = read('services/api/src/index.js');
const migration = read('services/api/migrations/0032_eino_material_chunks.sql');
const docs = read('services/api/docs/eino-pdf-retrieval.md');
assert.match(eino, /export async function adminIndexMaterialPdf/);
assert.match(eino, /retrieveStudentMaterialChunks\(ctx, student, message\)/);
assert.match(eino, /bytes\.length > 20 \* 1024 \* 1024/);
assert.match(eino, /String\.fromCharCode\(\.\.\.bytes\.slice\(0, 5\)\) !== '%PDF-'/);
assert.match(eino, /LIMIT 80/);
assert.match(eino, /rankStudentMaterialChunks\(rows, query, 4\)/);
assert.match(eino, /ORDER BY \(\$\{rankSql\}\) DESC, c\.chunk_index ASC/);
assert.match(eino, /m\.active = 1/);
assert.match(eino, /s\.department_id = \?/);
assert.ok(index.includes("path === '/admin/eino/materials/") || index.includes('/admin\\/eino\\/materials\\/[^/]+\\/index'));
assert.match(index, /adminIndexMaterialPdf\(ctx, path\.split\('\/'\)\[4\]\)/);
assert.match(migration, /CREATE TABLE IF NOT EXISTS eino_material_chunks/);
assert.match(migration, /UNIQUE\(material_id, chunk_index\)/);
assert.match(docs, /POST \/api\/v1\/admin\/eino\/materials/);
console.log('Eino PDF retrieval checks passed.');
